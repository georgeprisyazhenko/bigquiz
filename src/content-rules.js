// Значимые слова в ответе: токены без пунктуации, исключая служебные и местоимения.
export function contentWords(text) {
  return (text ?? '')
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .filter((w) => !FUNCTION_WORDS.has(w.toLowerCase().replace(/[.,!?;:()«»"'`]/g, '')))
}

// Проверяет один вариант ответа. Возвращает { ok, reasons }.
export function validateAnswerText(text) {
  const reasons = []
  const value = (text ?? '').trim()

  if (value.length > MAX_ANSWER_CHARS) {
    reasons.push(`длина ${value.length} > ${MAX_ANSWER_CHARS} символов`)
  }

  const words = contentWords(value)
  if (words.length > MAX_ANSWER_WORDS) {
    reasons.push(
      `значимых слов ${words.length} > ${MAX_ANSWER_WORDS} (служебные и местоимения не в счёт)`
    )
  }

  const allTokens = value.split(/\s+/).filter(Boolean)
  const longestWord = allTokens.reduce((max, word) => Math.max(max, word.length), 0)
  if (longestWord > MAX_WORD_CHARS) {
    reasons.push(`длинное слово ${longestWord} > ${MAX_WORD_CHARS} символов`)
  }

  return { ok: reasons.length === 0, reasons }
}

// Запрещённые тире: длинное «—» (U+2014) и среднее «–» (U+2013). В тексте вопросов,
// ответах и explanation допустим только дефис «-». LLM стабильно ставит тире вопреки
// инструкции, поэтому правило держим в коде (проверка + автозамена), а не на доверии.
export const FORBIDDEN_DASH_RE = /[—–]/

// Находит длинное/среднее тире в строке. Возвращает { ok, reasons }.
export function validateNoDashes(text) {
  const value = text ?? ''
  const ok = !FORBIDDEN_DASH_RE.test(value)
  return { ok, reasons: ok ? [] : ['содержит тире «—»/«–» вместо дефиса «-»'] }
}

// Заменяет все «—»/«–» на дефис «-» (для автозачистки при слиянии).
export function stripDashes(text) {
  return typeof text === 'string' ? text.replace(/[—–]/g, '-') : text
}

// Запрещённые Яндекс Играми темы (требования к содержанию, п. 3.4) - см. A.0 в
// docs/category-risks.md. Регэкспом ловим только надёжно детектируемую полосу:
// эзотерику/гадания/предсказания-как-практику. Политику и религию по ключевым
// словам не отсечь без ложных срабатываний - они остаются на правилах (A.0) и
// LLM-судье (флаг prohibitedYG в пайплайнах). Высокоточные термины эзотерики-как-
// ПРАКТИКИ; намеренно БЕЗ «маг»/«гадал»/«зодиак»/«пророчеств» — они ловили бы
// «магазин»/«угадал», астрономию (созвездия зодиака) и мифологию (пророчество в мифах,
// разрешённую по A.0).
export const PROHIBITED_TOPIC_RE =
  /гороскоп|астролог|гадани|гадалк|ворожб|нумеролог|ясновид|экстрасенс|спиритизм|эзотери|оккульт|хиромант|телекинез|чакр|рейки|фэн-?шуй|феншуй|таролог/i

// Проверяет текст (вопрос/ответ/explanation) на явный запрещённый по 3.4 контент.
export function validateNoProhibited(text) {
  const value = text ?? ''
  const m = value.match(PROHIBITED_TOPIC_RE)
  return m
    ? { ok: false, reasons: [`запрещённая тема ЯИ (3.4): «${m[0]}»`] }
    : { ok: true, reasons: [] }
}

// ─── Гейты уровня ВОПРОСА (проверяют 4 варианта вместе, а не один) ────────────────
// Их нельзя выразить через validateAnswerText (там один ответ) — нужен весь набор.
//
// ВАЖНО: границу слова `\b` НЕЛЬЗЯ использовать с кириллицей — в JS `\w` = [A-Za-z0-9_],
// кириллица для него «не-буква», поэтому `/\bоколо\b/` не матчит русское слово вообще.
// Поэтому сверяемся по НАБОРУ слов: режем на кириллические токены и проверяем членство.
const cyrWords = (text) => new Set((text ?? '').toLowerCase().match(/[а-яё]+/g) || [])
const hasAnyWord = (text, set) => {
  const ws = cyrWords(text)
  for (const w of set) if (ws.has(w)) return true
  return false
}

// Смягчители оценки величины. Если такое слово стоит в ≥2 вариантах из 4 — это
// «около-спам»: формулировка избыточна, слово не несёт значимости (на длину не влияет)
// и читается как шум. Убирать из ВСЕХ вариантов. Жёсткий гейт (прод чист).
export const HEDGE_WORDS = new Set(['около', 'примерно', 'приблизительно', 'порядка', 'почти'])

export function validateOptionsHomogeneous(answers) {
  const arr = Array.isArray(answers) ? answers : []
  const n = arr.filter((a) => hasAnyWord(a, HEDGE_WORDS)).length
  return n >= 2
    ? {
        ok: false,
        reasons: [`смягчитель величины («около/примерно») в ${n} из 4 вариантов - убрать из всех`],
      }
    : { ok: true, reasons: [] }
}

// Хедж ровно в ОДНОМ варианте → он выделяется на фоне «голых» трёх и читается как
// верный (живой кейс: «Около 4 лет» среди «15 лет / 7 лет / 30 лет» - реальное число
// часто паддят «около», дистракторы оставляют голыми). Это телеграф ответа, даже когда
// homogeneous-гейт (≥2) молчит. Мягкое предупреждение (бывают честные «Почти ноль»);
// чинить переформулировкой, а не авто-стрипом - стрип ломает грамматику («Около 4 лет»
// → нужно «4 года», а не «4 лет»). Жёстко не гейтим.
export function validateHedgeTell(answers) {
  const arr = Array.isArray(answers) ? answers : []
  const n = arr.filter((a) => hasAnyWord(a, HEDGE_WORDS)).length
  return n === 1
    ? {
        ok: false,
        reasons: [
          'смягчитель («около/примерно») ровно в 1 варианте - выделяет его как верный, убрать (переформулировать, не стрипать)',
        ],
      }
    : { ok: true, reasons: [] }
}

// Несколько открытых границ в ОДНУ сторону среди вариантов → диапазоны вложены и верных
// становится больше одного. Баг: «Более 600 граммов» и «Более 1 кг» (всё, что >1кг, также
// >600г). Норма — закрытая шкала «Менее X / X-Y / Более Z» (по одной границе с краёв).
// Считаем ТОЛЬКО открытый порог «более/менее + ЧИСЛО», не сравнительное «вдвое больше»
// (кратность — не диапазон). Жёсткий гейт.
const RANGE_LOWER_RE = /(более|больше|свыше)\s+\d/i
const RANGE_UPPER_RE = /(менее|меньше)\s+\d/i

export function validateNumericRanges(answers) {
  const arr = Array.isArray(answers) ? answers : []
  const lower = arr.filter((a) => RANGE_LOWER_RE.test(a ?? '')).length
  const upper = arr.filter((a) => RANGE_UPPER_RE.test(a ?? '')).length
  const reasons = []
  if (lower >= 2)
    reasons.push(`${lower} варианта с открытой нижней границей («более N…») - вложенные диапазоны`)
  if (upper >= 2)
    reasons.push(`${upper} варианта с открытой верхней границей («менее N…») - вложенные диапазоны`)
  return { ok: reasons.length === 0, reasons }
}

// Перечисление двух однородных слов через запятую → лучше через союз «и» («Реки, проливы»
// → «Реки и проливы»). «и» — служебное, на лимит длины не влияет. НЕ трогаем: десятичную
// запятую (1,5), запятую перед придаточным (как/что/чтобы…), цитаты в кавычках, варианты,
// где союз уже есть. Мягкое предупреждение (не жёсткий гейт — возможны ложные срабатывания).
// Верный ответ - единственное «не-круглое» число среди вариантов → он угадывается
// (реальное значение обычно не кратно 10, а выдуманные дистракторы - кратны: 1500/900/750
// против 1227). Ловим, ЗНАЯ correctAnswerIndex: если ровно один вариант не делится на 10 и
// это верный - флаг. Мягкое предупреждение (зависит от индекса, бывают честные исключения).
const leadingInt = (s) => {
  const m = String(s ?? '')
    .replace(/\s/g, '')
    .match(/^-?\d+/)
  return m ? parseInt(m[0], 10) : null
}

export function validateNumericTell(answers, correctIndex) {
  const arr = Array.isArray(answers) ? answers : []
  const nums = arr.map(leadingInt)
  if (nums.length !== 4 || nums.some((n) => n === null)) return { ok: true, reasons: [] } // не все числовые
  const nonRound = nums.map((n, i) => ({ n, i })).filter(({ n }) => n % 10 !== 0)
  return nonRound.length === 1 && nonRound[0].i === correctIndex
    ? {
        ok: false,
        reasons: [
          'верный - единственное «не-круглое» число (угадывается); сделай дистракторы тоже не кратными 10',
        ],
      }
    : { ok: true, reasons: [] }
}

// Антипаттерн «экзамен» (эвристика, мягкая): вопрос начинается с «Почему/Зачем» И ВСЕ 4
// ответа длиннее 2 значимых слов → это 4 объяснения-эссе, а не выбор; кандидат на переворот
// угла (идентичность/число в ОТВЕТ). Эвристика приблизительная (честное «почему» с короткими
// ответами не триггерится; короткий ответ-сущность тоже) → мягкое предупреждение, не гейт.
// `\b` с кириллицей НЕ работает (см. выше) — конец слова ловим как «не followed by кириллицей».
const EXAM_Q_RE = /^\s*(почему|зачем)(?![а-яё])/i

export function validateExamShape(question, answers) {
  const arr = Array.isArray(answers) ? answers : []
  if (arr.length !== 4) return { ok: true, reasons: [] }
  const isWhy = EXAM_Q_RE.test(question ?? '')
  const allLong = arr.every((a) => contentWords(a).length > 2)
  return isWhy && allLong
    ? {
        ok: false,
        reasons: [
          '«Почему/Зачем X?» + все 4 ответа длиннее 2 слов = эссе-экзамен; переверни угол (идентичность/число в ответ)',
        ],
      }
    : { ok: true, reasons: [] }
}

const CONJ_WORDS = new Set(['и', 'или', 'да'])

export function validateEnumeration(text) {
  const v = (text ?? '').trim()
  // кавычки-цитаты, десятичная запятая, запятая перед придаточным — не перечисление
  if (
    /[«»"]/.test(v) ||
    /\d,\d/.test(v) ||
    /,\s*(как|что|чтобы|где|когда|потому)(?![а-яё])/i.test(v)
  )
    return { ok: true, reasons: [] }
  if (hasAnyWord(v, CONJ_WORDS)) return { ok: true, reasons: [] } // союз уже есть
  return /[А-Яа-яЁё]+\s*,\s*[А-Яа-яЁё]+/.test(v)
    ? { ok: false, reasons: ['перечисление через запятую - соединить союзом «и»'] }
    : { ok: true, reasons: [] }
}
